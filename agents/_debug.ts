import { AgentRelay } from '@agent-relay/sdk';
const url = 'https://cast.agentrelay.com';
const r = Math.random().toString(36).slice(2, 6);
const ws = await AgentRelay.createWorkspace({ name: `dbg${r}`, baseUrl: url });
const key = ws.workspaceKey!;
const a: any = await ws.workspace.register({ name: `a${r}`, type: 'agent' }, { strict: true });
const b: any = await ws.workspace.register({ name: `b${r}`, type: 'agent' }, { strict: true });
const otRes: any = await (await fetch(`${url}/v1/observer-tokens`, { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` }, body: JSON.stringify({ name: 'x', scopes: ['stream:read', 'messages:read', 'channels:read', 'dms:read'] }) })).json();
const ot = otRes.data.token;
const seen: any[] = [];
const sock = new WebSocket(`wss://cast.agentrelay.com/v1/ws?token=${ot}`);
sock.onopen = () => console.log('ws open');
sock.onclose = (e) => console.log('ws close', e.code, e.reason);
sock.onerror = (e: any) => console.log('ws err', e.message);
sock.onmessage = (ev) => seen.push(String(ev.data).slice(0, 300));
await new Promise((res) => setTimeout(res, 2000));
const aR = new AgentRelay({ baseUrl: url, agentToken: a.token });
const A: any = await aR.workspace.reconnect({ apiToken: a.token });
const m = await A.messages.dm({ to: `b${r}`, text: 'hi', metadata: { kind: 'handoff', epoch: 2 } });
console.log('sent dm', JSON.stringify(m).slice(0, 400));
await A.channels.create({ name: `c${r}` });
const cm = await A.sendMessage({ to: `#c${r}`, text: 'chan', metadata: { kind: 'checkpoint' } });
const g = await (await fetch(`${url}/v1/messages/${m.id}`, { headers: { authorization: `Bearer ${a.token}` } })).json();
console.log('GET dm', JSON.stringify(g).slice(0, 500));
const bR = new AgentRelay({ baseUrl: url, agentToken: b.token });
const B: any = await bR.workspace.reconnect({ apiToken: b.token });
const ib = await B.inbox.list({ agentName: `b${r}` });
console.log('inbox item', JSON.stringify(ib.items[0]).slice(0, 700));
await new Promise((res) => setTimeout(res, 2500));
console.log('observer seen', seen.length, seen.slice(0, 4));
process.exit(0);
